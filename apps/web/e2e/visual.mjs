// Visual walkthrough for AI Studio (uses whatever AI backend the API is configured with).
import { chromium } from 'playwright';
const BASE = process.env.BASE_URL ?? 'http://127.0.0.1:4000';
const OUT = process.env.SHOT_DIR ?? './shots/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const shot = (n, full = false) => p.screenshot({ path: OUT + n + '.png', fullPage: full });
await p.goto(BASE + '/'); await p.waitForTimeout(900); await shot('01-public');
await p.goto(BASE + '/login'); await p.waitForTimeout(600); await shot('02-login');
await p.getByLabel('Work email').fill('hse.engineer@demo.forgehse.local');
await p.getByLabel('Password').fill('DemoUser2026!');
await p.getByRole('button', { name: 'Sign in' }).click();
await p.waitForURL(/\/app/); await p.getByRole('heading', { name: 'Open risk' }).waitFor(); await p.waitForTimeout(1200); await shot('03-dashboard');
await p.keyboard.press('Control+k'); await p.keyboard.type('scaffold inspection'); await p.waitForTimeout(400); await shot('04-palette');
await p.keyboard.press('Escape');
await p.goto(BASE + '/app/studio'); await p.waitForTimeout(1200); await shot('05-studio-welcome');
await p.getByLabel('Message').fill('Which high or critical items are still open?');
await p.keyboard.press('Enter');
await p.locator('.msg.assistant .msg-meta').first().waitFor({ timeout: 20000 }); await p.waitForTimeout(400); await shot('06-studio-answer');
await p.getByRole('button', { name: 'Checklist', exact: true }).click();
await p.getByLabel('Message').fill('Pre-use inspection for a mobile elevating work platform on Tower site');
await p.keyboard.press('Enter');
await p.locator('.canvas .paper').waitFor({ timeout: 20000 }); await p.waitForTimeout(500); await shot('07-studio-checklist');
await p.getByRole('button', { name: 'Poster', exact: true }).click();
await p.getByLabel('Message').fill('Harness use when working at height');
await p.keyboard.press('Enter');
await p.locator('.canvas .art-frame img').waitFor({ timeout: 20000 }); await p.waitForTimeout(500); await shot('08-studio-poster');
await p.getByRole('button', { name: 'Flowchart', exact: true }).click();
await p.getByLabel('Message').fill('Confined space entry permit');
await p.keyboard.press('Enter');
await p.waitForTimeout(2500); await shot('09-studio-flow');
await p.goto(BASE + '/app/studio/library'); await p.waitForTimeout(900); await shot('10-library');
await p.locator('.lib-card a').first().click(); await p.waitForTimeout(900); await shot('11-item', true);
await p.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
await p.goto(BASE + '/app/studio'); await p.evaluate(() => { localStorage.setItem('fhse.theme', 'dark'); }); await p.reload(); await p.waitForTimeout(1200); await shot('12-studio-dark');
await p.goto(BASE + '/app'); await p.waitForTimeout(1200); await shot('13-dashboard-dark');
await p.goto(BASE + '/app/account'); await p.waitForTimeout(500); await shot('14-account-dark', true);
const m = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, storageState: await ctx.storageState() });
const mp = await m.newPage();
await mp.goto(BASE + '/app/studio'); await mp.waitForTimeout(1200); await mp.screenshot({ path: OUT + '15-mobile-studio.png' });
await mp.goto(BASE + '/app'); await mp.waitForTimeout(1200); await mp.screenshot({ path: OUT + '16-mobile-dashboard.png' });
console.log('errors:', errs.length ? errs : 'none');
await b.close();
