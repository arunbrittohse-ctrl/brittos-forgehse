/**
 * FORGEHSE local rules engine: answers every AI request type deterministically from the curated
 * topic library, the organisation's own context and the live records the server already
 * authorised. No language model, no network, no cost. Output is always labelled as rules-based
 * and goes through the same schema validation and human review as model output.
 */
import { DOCUMENT_TYPES, DOCUMENT_TYPE_LABELS, type DocumentType, type Checklist, type HseDocument, type Poster, type Flowchart, type DocumentReview } from '@forgehse/shared';
import type { MessagesRequest, ContentBlock } from '../../claude';
import { matchTopic, TOPICS, GENERAL_TOPIC, type Topic } from './knowledge';

export const LOCAL_MODEL = 'forgehse-local-rules-v1';
export const LOCAL_NOTE = 'Generated by the FORGEHSE local rules engine (no AI model). Review and adapt before use.';
const LIMIT_NOTE = 'Confirm every numeric limit marked [confirm limit per project procedure] against the approved project procedures and applicable regulations.';
const SOURCE_LINE = '_Source: FORGEHSE local guidance library — rules-based, no AI model. Confirm against your project procedures and applicable regulations._';

