const ACT_RE = /\b(not wearing|without (a |his |her |their )?(harness|helmet|ppe|gloves|glasses)|no harness|not clipped|unclipped|removed|bypass\w*|standing under|walking under|using (a |his |her )?(phone|mobile)|smoking|climbing|jumped|short ?cut|horseplay|ignored|overrid\w*)\b/i;
const POSITIVE_RE = /\b(good practice|well done|excellent|positive|correctly (used|wearing|installed)|commend\w*)\b/i;
const NEAR_MISS_RE = /\b(near miss|nearly|almost (hit|fell|struck)|narrowly)\b/i;
const IMMEDIATE_RE = /[^.]*\b(stopped|removed|barricaded|corrected|instructed|isolated|cordoned|fixed|replaced)\b[^.]*\.?/i;
const LOCATION_RE = /\b(?:at|on|in|near|beside|inside)\s+((?:level|floor|zone|area|block|gate|grid|basement|roof|podium|ch|chainage|tower|building|bay|room|stair\w*)\b[^,.;]{0,40})/i;

export function localDraftObservation(input: string, size: number, cats: string[]) {
  const t = matchTopic(input);
  const type = POSITIVE_RE.test(input) ? 'positive' : NEAR_MISS_RE.test(input) ? 'near_miss_observed' : ACT_RE.test(input) ? 'unsafe_act' : 'unsafe_condition';
  const freq = /\b(repeated|again|daily|always|several|multiple|many|every day)\b/i.test(input) ? 4 : /\b(isolated|once|single|briefly)\b/i.test(input) ? 2 : 3;
  const likelihood = type === 'positive' ? 1 : scale(freq, size);
  const severity = type === 'positive' ? 1 : scale(t.baseSeverity, size);
  const loc = input.match(LOCATION_RE)?.[1]?.trim() ?? '';
  const imm = input.match(IMMEDIATE_RE)?.[0]?.trim() ?? '';
  const category = cats.includes(t.category) ? t.category : cats.includes('Other') ? 'Other' : (cats[0] ?? t.category);
  const missing = [
    !loc ? 'Exact location (level, grid or area)' : '',
    !imm ? 'Immediate action taken at the time' : '',
    !/\b(\d{1,2}[:.]\d{2}|am|pm|morning|afternoon|shift)\b/i.test(input) ? 'Time of the observation' : '',
    'Photo evidence',
  ].filter(Boolean);
  return {
    type, hazardCategory: category, location: loc, activity: t.id === 'general' ? '' : t.label,
    description: clip(cap(oneLine(input)), 2000), immediateAction: imm,
    likelihood, severity,
    ratingRationale: type === 'positive'
      ? 'Positive observation — no risk rating needed.'
      : `Rules-based rating: severity reflects the credible worst outcome typical of ${t.label.toLowerCase()} (${t.hazards[0]?.consequence.toLowerCase() ?? 'injury'}); likelihood ${freq >= 4 ? 'raised because the description suggests a repeated condition' : freq <= 2 ? 'lowered because the description suggests an isolated case' : 'set to "possible" by default'}. Adjust both to what you actually observed.`,
    suggestedCorrectiveAction: t.corrective[0]?.action ?? '',
    missingInformation: missing,
  };
}

function capaFor(records: unknown) {
  const o = (records as { observation?: { hazardCategory?: string; description?: string } } | undefined)?.observation ?? {};
  const t = TOPICS.find((x) => x.category === o.hazardCategory) ?? matchTopic(`${o.hazardCategory ?? ''} ${o.description ?? ''}`);
  return {
    correctiveActions: t.corrective,
    preventiveActions: t.preventive,
    likelyRootCauses: t.rootCauses.map((r) => `${r} (to be confirmed)`),
    cautions: ['These are standard actions from the FORGEHSE local library for this hazard type, not an analysis of this specific record. Confirm they fit the actual conditions before assigning them.', LOCAL_NOTE],
  };
}

function summaryMarkdown(records: unknown): string {
  const r = (records ?? {}) as { statistics?: Record<string, number>; byHazardCategory?: { category: string; n: number }[]; highestRiskRecords?: { refNo: string; hazardCategory: string; riskBand: string; status: string }[] };
  const s = r.statistics ?? {};
  const top = r.byHazardCategory ?? [];
  const high = (r.highestRiskRecords ?? []).filter((x) => x.riskBand === 'high' || x.riskBand === 'critical').slice(0, 5);
  const lines = [
    '## HSE observations — last 30 days',
    '',
    `- **${s.total ?? 0}** observations reported (${s.unsafeActs ?? 0} unsafe acts, ${s.unsafeConditions ?? 0} unsafe conditions)`,
    `- **${s.stillOpen ?? 0}** still open, **${s.overdue ?? 0}** overdue`,
    `- **${s.highOrCritical ?? 0}** rated high or critical`,
    '',
  ];
  if (top.length) lines.push('### Most frequent hazard categories', '', ...top.slice(0, 5).map((c) => `- ${c.category}: ${c.n}`), '');
  if (high.length) lines.push('### High and critical items', '', '| Ref | Hazard | Risk | Status |', '|---|---|---|---|', ...high.map((x) => `| ${x.refNo} | ${x.hazardCategory} | ${x.riskBand} | ${x.status.replace(/_/g, ' ')} |`), '');
  const focus = top[0] ? TOPICS.find((x) => x.category === top[0]!.category) : undefined;
  lines.push('### Suggested focus', '', '- Verify closure of high and critical items on site, not only on paper.', '- Follow up overdue actions with their owners this week.');
  if (focus) lines.push(`- ${focus.label} is the most frequent category — re-brief: ${focus.keyControls.slice(0, 2).join('; ').toLowerCase()}.`);
  lines.push('', '_Figures computed directly from your records; wording from the FORGEHSE local rules engine (no AI model)._');
  return lines.join('\n');
}

export function guidanceMarkdown(question: string): string {
  const t = matchTopic(question);
  if (t === GENERAL_TOPIC) {
    return [
      'The local rules engine answers from a fixed FORGEHSE guidance library; it cannot answer open questions the way a language model can.',
      '',
      `Topics covered: ${TOPICS.filter((x) => x !== GENERAL_TOPIC).map((x) => x.label.toLowerCase()).join(', ')}.`,
      '',
      'Try for example “key controls for hot work”, or ask me to search your observations or create a checklist, toolbox talk, poster or flowchart.',
      '',
      SOURCE_LINE,
    ].join('\n');
  }
  return [
    `## ${t.label}: key controls`,
    '',
    ...t.keyControls.map((c, i) => `${i + 1}. ${c}`),
    '',
    '### Typical hazards',
    ...t.hazards.map((h) => `- **${h.hazard}** — ${h.consequence.toLowerCase()}`),
    '',
    '> Numeric limits (heights, distances, durations, gas or wind values) must come from your approved project procedures and the regulations that apply to the project.',
    '',
    SOURCE_LINE,
  ].join('\n');
}

