/* ------------------------------------------------------------------ request reading */

function texts(blocks: ContentBlock[]): string {
  return blocks.filter((b): b is Extract<ContentBlock, { type: 'text' }> => b.type === 'text').map((b) => b.text).join('\n');
}
function contextText(body: MessagesRequest): string {
  return [...body.system.map((s) => s.text), ...body.messages.filter((m) => m.role === 'user').map((m) => texts(m.content))].join('\n');
}
function tag(text: string, name: string): string {
  const m = text.match(new RegExp(`<${name}>\\n?([\\s\\S]*?)\\n?</${name}>`));
  return m ? m[1]!.trim() : '';
}
function matrixSize(body: MessagesRequest): number {
  const m = contextText(body).match(/Risk matrix:\s*(\d+)\s*[×x]/);
  const n = m ? Number(m[1]) : 5;
  return n >= 2 && n <= 10 ? n : 5;
}
function categories(body: MessagesRequest): string[] {
  const m = contextText(body).match(/Hazard categories[^:]*:\s*(.+)/);
  return m ? m[1]!.split('|').map((s) => s.trim()).filter(Boolean) : [];
}
/** Ratings in the library are on a 5-point scale; map them onto the organisation's matrix. */
function scale(n: number, size: number): number {
  return Math.max(1, Math.min(size, Math.round((n * size) / 5)));
}
const clip = (s: string, n: number) => (s.length <= n ? s : s.slice(0, n - 1).trimEnd() + '…');
const oneLine = (s: string) => s.replace(/\s+/g, ' ').trim();
const cap = (s: string) => (s ? s[0]!.toUpperCase() + s.slice(1) : s);

