export function localReview(docText: string, fileName: string): DocumentReview {
  const text = docText.slice(0, 200_000);
  const present = REVIEW_CHECKS.filter((c) => c.re.test(text));
  const missing = REVIEW_CHECKS.filter((c) => !c.re.test(text));
  const t = matchTopic(text);
  const type = /method statement/i.test(text) ? 'Method statement' : /risk assessment/i.test(text) ? 'Risk assessment' : /emergency/i.test(text) ? 'Emergency plan' : /procedure/i.test(text) ? 'Procedure' : 'HSE document';
  const rating: DocumentReview['overallRating'] = missing.some((m) => m.severity === 'critical') ? 'inadequate' : missing.some((m) => m.severity === 'major') ? 'needs_improvement' : 'adequate';
  const words = text.split(/\s+/).filter(Boolean).length;
  return {
    documentTitle: clip(fileName || 'Uploaded document', 200),
    documentType: type,
    summary: clip(`Automated completeness screen of a ${words.toLocaleString('en')}-word ${type.toLowerCase()} (main topic detected: ${t.label.toLowerCase()}). ${present.length} of ${REVIEW_CHECKS.length} expected elements were found by keyword; ${missing.length} appear to be missing. This is a keyword-based screen by the local rules engine — it does not judge technical adequacy, so a competent person must still review the content.`, 1200),
    overallRating: rating,
    strengths: present.slice(0, 10).map((p) => `Addresses: ${p.name.toLowerCase()}`),
    findings: missing.map((m) => ({ severity: m.severity, section: m.name, issue: `No clear reference to ${m.name.toLowerCase()} was found.`, recommendation: m.rec })),
    missingElements: missing.map((m) => m.name).slice(0, 15),
    questionsForAuthor: ['Has this document been checked against the current site conditions and approved method?', `Are the ${t.label.toLowerCase()} controls verified on site before work starts?`, LOCAL_NOTE],
  };
}

