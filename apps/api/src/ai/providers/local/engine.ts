const CREATE_RE = /\b(create|make|prepare|draft|generate|write|produce|build|design)\b/i;

function docTypeFrom(q: string): DocumentType | undefined {
  const pairs: [RegExp, DocumentType][] = [
    [/toolbox|tbt/i, 'toolbox_talk'], [/method statement|\bms\b/i, 'method_statement'], [/risk assessment|\bra\b|jsa|jha|job safety/i, 'risk_assessment'],
    [/procedure|sop|swp/i, 'safe_work_procedure'], [/emergency|erp/i, 'emergency_response_plan'], [/inspection report/i, 'inspection_report'],
    [/incident report|investigation/i, 'incident_report'], [/hse plan/i, 'hse_plan_section'], [/handout|training/i, 'training_handout'],
  ];
  return pairs.find(([re]) => re.test(q))?.[1];
}

export function planResponse(body: MessagesRequest): Plan {
  const size = matrixSize(body);
  const forced = body.tool_choice?.type === 'tool' ? body.tool_choice.name : null;
  const firstUser = body.messages.find((m) => m.role === 'user');

  // Studio generators: one forced emit_* tool.
  if (forced?.startsWith('emit_')) {
    const kind = forced.slice(5);
    const request = texts(firstUser?.content ?? []);
    const brief = tag(request, 'brief') || request;
    const dt = request.match(/Document type:[^(]*\((\w+)\)/)?.[1] as DocumentType | undefined;
    let input: unknown;
    if (kind === 'checklist') input = localChecklist(brief);
    else if (kind === 'document') input = localDocument(brief, dt && (DOCUMENT_TYPES as readonly string[]).includes(dt) ? dt : (docTypeFrom(brief) ?? 'other'), size);
    else if (kind === 'poster') input = localPoster(brief);
    else if (kind === 'flowchart') input = localFlowchart(brief);
    else if (kind === 'review') {
      const doc = firstUser?.content.find((c): c is Extract<ContentBlock, { type: 'document' }> => c.type === 'document');
      if (!doc || doc.source.type !== 'text' || !doc.source.data.trim()) {
        throw new LocalEngineError('ai_local_unsupported', 'The local rules engine can review Word (.docx) and text files only. Upload the document in one of those formats, or ask your administrator to enable a model provider.');
      }
      input = localReview(doc.source.data, doc.title ?? '');
    } else throw new LocalEngineError('ai_local_unsupported', 'This request type is not available in local mode.');
    return { tools: [{ name: forced, input }] };
  }

  // /api/ai/assist: single message beginning with TASK:
  const first = texts(firstUser?.content ?? []);
  const task = first.match(/^TASK:\s*(\w+)/)?.[1];
  if (task && body.messages.length === 1) {
    const input = tag(first, 'user_input');
    const records = (() => { try { return JSON.parse(tag(first, 'records') || 'null'); } catch { return null; } })();
    if (task === 'draft_observation') return { text: JSON.stringify(localDraftObservation(input, size, categories(body))) };
    if (task === 'suggest_capa') return { text: JSON.stringify(capaFor(records)) };
    if (task === 'summarize_observations') return { text: summaryMarkdown(records) };
    return { text: guidanceMarkdown(input) };
  }

  // AI Studio chat with tools.
  const last = body.messages[body.messages.length - 1];
  const toolResult = last?.content.find((c): c is Extract<ContentBlock, { type: 'tool_result' }> => c.type === 'tool_result');
  if (toolResult) return { text: describeToolResult(toolResult.content) };
  const q = texts(last?.content ?? []);
  if (body.tool_choice?.type === 'none') return { text: guidanceMarkdown(q) };
  const lq = q.toLowerCase();
  const kind = /checklist/.test(lq) ? 'checklist' : /poster/.test(lq) ? 'poster' : /flow ?chart|process (map|diagram)/.test(lq) ? 'flowchart' : docTypeFrom(lq) ? 'document' : null;
  if (kind && CREATE_RE.test(lq)) {
    const documentType = kind === 'document' ? docTypeFrom(lq) : undefined;
    return { text: 'Preparing that in Studio now — it will open as a draft for your review.', tools: [{ name: 'create_studio_draft', input: { kind, brief: clip(q.trim(), 1000), ...(documentType ? { documentType } : {}) } }] };
  }
  if (/\b(report|i saw|i observed|observed|spotted|found)\b/.test(lq) && !/\b(show|list|which|how many|summar)/.test(lq)) {
    return { text: 'I have prepared an observation report from your description. Check every field before you submit it.', tools: [{ name: 'prepare_observation', input: { notes: clip(q.trim(), 2000) } }] };
  }
  if (/\b(summar\w*|statistic\w*|how many|trend\w*|kpi|performance|this month|last \d+ days)\b/.test(lq)) {
    const days = Number(lq.match(/last (\d+) days/)?.[1] ?? 30);
    return { text: 'Checking your live figures.', tools: [{ name: 'hse_statistics', input: { days: Math.min(730, Math.max(1, days)) } }] };
  }
  if (/\b(show|list|find|search|which|where|open|overdue|high|critical)\b/.test(lq)) {
    const t = matchTopic(lq);
    const query = t === GENERAL_TOPIC ? '' : (lq.match(new RegExp(t.keywords.source, 'i'))?.[0] ?? t.label);
    return { text: 'Searching your records.', tools: [{ name: 'search_observations', input: { query, status: /overdue/.test(lq) ? 'overdue' : /closed/.test(lq) ? 'closed' : /open|outstanding/.test(lq) ? 'open' : 'any', riskBand: /high|critical/.test(lq) ? 'high_or_critical' : 'any' } }] };
  }
  return { text: guidanceMarkdown(q) };
}

function describeToolResult(raw: string): string {
  let data: Record<string, any> = {};
  try { data = JSON.parse(raw); } catch { /* not JSON */ }
  if (Array.isArray(data.records)) {
    if (!data.matched) return `No matching records were found in your scope for that search.\n\n${SOURCE_LINE}`;
    const rows = data.records.slice(0, 10).map((r: any) => `| [${r.refNo}] | ${r.hazardCategory} | ${r.location || r.site} | ${r.riskBand} | ${String(r.status).replace(/_/g, ' ')} |`);
    return [`**${data.matched} matching record${data.matched === 1 ? '' : 's'}** in your scope, highest risk first.`, '', '| Ref | Hazard | Location | Risk | Status |', '|---|---|---|---|---|', ...rows, '', 'Open a reference to see the full record and its evidence.', '', SOURCE_LINE].join('\n');
  }
  if (data.periodDays) {
    const top = (data.byHazardCategory ?? [])[0];
    const rate = data.closedWithDueDate ? Math.round((100 * data.closedOnTime) / data.closedWithDueDate) : null;
    return [`### Last ${data.periodDays} days`, '',
      `- **${data.reportedInPeriod ?? 0}** observations reported (${data.unsafeActs ?? 0} unsafe acts, ${data.unsafeConditions ?? 0} unsafe conditions)`,
      `- **${data.openNow ?? 0}** open now, **${data.overdueNow ?? 0}** overdue`,
      `- **${data.highOrCriticalOpen ?? 0}** high or critical still open`,
      `- On-time closure: ${rate === null ? 'not available (no closed items with a due date)' : `${rate}%`}`,
      top ? `- Most frequent hazard: ${top.category} (${top.n})` : '', '', '_Figures computed live from your records._', '', SOURCE_LINE].filter((l) => l !== '').join('\n');
  }
  if (data.status === 'form_opened') return 'The pre-filled report is open. It has **not** been submitted — check it and submit it yourself.';
  return 'Your draft is being prepared in Studio. It stays a draft until a reviewer approves it.';
}
