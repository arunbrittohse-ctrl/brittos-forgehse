// Embed the built web app (apps/web/dist, without source maps) into the Compute server bundle.
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dist = path.join(root, 'apps/web/dist');
const out = {};
async function walk(dir) {
  for (const f of await readdir(dir)) {
    const p = path.join(dir, f);
    if ((await stat(p)).isDirectory()) await walk(p);
    else if (!f.endsWith('.map')) out['/' + path.relative(dist, p).split(path.sep).join('/')] = (await readFile(p)).toString('base64');
  }
}
await walk(dist);
if (!out['/index.html']) throw new Error('apps/web/dist/index.html missing — build the web app first');
await writeFile(path.join(root, 'deploy/compute/_web.generated.ts'), `// Generated by scripts/compute/gen-web.mjs — do not edit.\nexport const WEB_FILES: Record<string, string> = ${JSON.stringify(out)};\n`);
console.log(`embedded ${Object.keys(out).length} web files`);
