// Netlify build step: embed the SQL migrations into the server function bundle
// (serverless bundles cannot read the migrations folder at runtime).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'apps/api/migrations');
const files = (await readdir(dir)).filter((f) => f.endsWith('.up.sql')).sort();
const list = [];
for (const f of files) list.push({ version: f.replace('.up.sql', ''), sql: await readFile(path.join(dir, f), 'utf8') });
await writeFile(path.join(root, 'netlify/functions/_migrations.generated.ts'), `// Generated by scripts/netlify/gen-migrations.mjs — do not edit.\nexport const MIGRATIONS: { version: string; sql: string }[] = ${JSON.stringify(list)};\n`);
console.log(`embedded ${list.length} migrations`);
